// Normalize a restaurant from either the backend DTO or mock data into the
// shape the UI expects, guaranteeing a `foodType` ("veg" | "non-veg").
// The backend exposes `vegOnly` (no per-restaurant foodType), so the tag is
// derived: a pure-veg restaurant is "veg", everything else is "non-veg".
export function normalizeRestaurantData(list: Restaurant[]): Restaurant[] {
  return list.map((r) => ({
    ...r,
    foodType: r.foodType ?? (r.vegOnly ? "veg" : "non-veg"),
  }));
}
